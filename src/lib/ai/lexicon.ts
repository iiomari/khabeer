/**
 * Arabic normalisation: strips diacritics and tatweel and unifies the letter forms
 * people type interchangeably, so "سلسلة إمداد" and "سلسله امداد" both match.
 */
export function normalizeArabic(text: string): string {
  return text
    .replace(/[ً-ْـ]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/\s+/g, " ")
    .toLowerCase()
    .trim();
}

/** Scores every category against the text and returns them best-first. */
export function scoreCategories(text: string): { slug: string; score: number }[] {
  const normalized = normalizeArabic(text);

  return Object.entries(CATEGORY_SIGNALS)
    .map(([slug, signals]) => {
      let score = 0;
      for (const keyword of signals.keywords) {
        if (normalized.includes(normalizeArabic(keyword))) score += 1;
      }
      return { slug, score };
    })
    .sort((a, b) => b.score - a.score);
}
